fruits.append("Kiwi")
# Add "Orange" to the beginning of the list
fruits.insert(0, "Orange")
# Add "Peach" to the 25th position of the list
fruits.insert(25, "Peach")
# Remove "Melon" from the list
fruits.remove("Melon")
